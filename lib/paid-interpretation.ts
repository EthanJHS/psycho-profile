function detectCrossInsights(hexaco: HexacoScores): CrossInsight[] {
  const levels = {} as Record<HexacoFactor, FactorLevel>
  for (const [f, v] of Object.entries(hexaco) as [HexacoFactor, number][]) {
    levels[f] = hl(v)
  }
  return CROSS_RULES
    .filter(r => r.cond(levels))
    .sort((a, b) => a.priority - b.priority)
    .slice(0, 3)
    .map(r => r.insight)
}

