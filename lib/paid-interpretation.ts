export interface CrossInsight {
  tag: string        // 짧은 패턴 이름, 예: 'O↑ × E↓'
  title: string      // 한 줄 제목
  body: string       // 2~3문장 임상적 해석
  type: 'strength' | 'tension' | 'rare'  // 강점 조합 / 긴장 조합 / 희귀 조합
}

export interface SituationalPrediction {
  context: '직장·팀' | '스트레스' | '대인관계'
  icon: string
  headline: string    // 한 줄 핵심 예측
  behaviors: string[] // 구체적 행동 패턴 2~3가지
  watchout: string    // 이 상황에서 특히 주의할 점
}

export interface TripleConflict {
  personalityRiasec: RiasecType   // 성격 기반 진로 TOP5의 지배적 RIASEC
  interestRiasec: RiasecType      // Holland 흥미 검사 1위
  aptitudeDominant: string        // 학문 적성 계열
  aligned: boolean                // 세 나침반이 같은 방향이면 true
  narrative: string               // 충돌 또는 일치 해석 텍스트
  bridgeRoles: string[]           // 두 성향을 동시에 살리는 역할 예시
}

export interface PaidInterpretation {
  // 핵심 정체성 한 줄
  headline: string
  // HEXACO 패턴 키 (예: 'HO', 'OC' …)
  patternKey: string
  // HEXACO 패턴
  hexacoPattern: {
    title: string
    portrait: string
    shadow: string
    topFacets: { label: string; score: number; insight: string }[]
    lowFacets: { label: string; score: number; insight: string }[]
    crossInsights: CrossInsight[]
  }
  // 상황별 행동 예측
  situationalPredictions: SituationalPrediction[]
  // RIASEC 해석
  riasecProfile: {
    hollandCode: string
    title: string
    portrait: string
    fitEnvironments: string[]
    misfitEnvironments: string[]
  }
  // 학문 적성
  aptitudeBreakdown: AptitudeRatio
  // HEXACO × RIASEC × 적성 교차 종합 분석
  crossDomainSynthesis: CrossDomainSynthesis
  // 통합 결론
  synthesis: {
    coreIdentity: string
    careerCompass: string
    growthEdge: string
    alignment: 'high' | 'mid' | 'low'
    alignmentNote: string
  }
}

