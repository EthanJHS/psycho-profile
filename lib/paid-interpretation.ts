export function computeTripleConflict(
  personalityRiasec: RiasecType,
  interestRiasec: RiasecType,
  aptDominant: AptDomain,
): TripleConflict {
  const aptCluster = APT_RIASEC_CLUSTER[aptDominant]
  const aptAligned = aptCluster.includes(interestRiasec)
  const personalityInterestAligned = personalityRiasec === interestRiasec

  if (personalityInterestAligned && aptAligned) {
    return {
      personalityRiasec,
      interestRiasec,
      aptitudeDominant: aptDominant,
      aligned: true,
      narrative: `성격(${RIASEC_KO[personalityRiasec]}), 흥미(${RIASEC_KO[interestRiasec]}), 적성(${aptDominant}) — 세 나침반이 같은 방향을 가리킵니다. 이 일관성은 강점입니다. 진로 선택에서 내·외적 갈등이 적고, 에너지가 한 방향으로 집중됩니다. 이 조합이 가장 강하게 빛나는 경로를 깊이 파고드는 것이 최선의 전략입니다.`,
      bridgeRoles: [],
    }
  }

  // 성격 vs 흥미 충돌이 더 중요한 갈등
  const piKey = `${personalityRiasec}-${interestRiasec}`
  const reverseKey = `${interestRiasec}-${personalityRiasec}`
  const piConflict = PERSONALITY_INTEREST_CONFLICT[piKey] ?? PERSONALITY_INTEREST_CONFLICT[reverseKey]

  if (!personalityInterestAligned && piConflict) {
    const aptNote = !aptAligned
      ? ` 학문 적성(${aptDominant})까지 고려하면 선택지가 더 좁혀집니다 — 세 조건을 모두 충족하는 '교차점'을 찾는 것이 핵심 전략입니다.`
      : ''
    return {
      personalityRiasec,
      interestRiasec,
      aptitudeDominant: aptDominant,
      aligned: false,
      narrative: piConflict.narrative + aptNote,
      bridgeRoles: piConflict.bridges,
    }
  }

  // 흥미 vs 적성 충돌
  const aiKey = `${interestRiasec}-${aptDominant}`
  const aiConflict = APT_INTEREST_CONFLICT[aiKey]
  if (!aptAligned && aiConflict) {
    return {
      personalityRiasec,
      interestRiasec,
      aptitudeDominant: aptDominant,
      aligned: false,
      narrative: aiConflict.narrative,
      bridgeRoles: aiConflict.bridges,
    }
  }

  // 충돌 패턴이 없거나 경미한 경우 — 대체 텍스트
  return {
    personalityRiasec,
    interestRiasec,
    aptitudeDominant: aptDominant,
    aligned: true,
    narrative: `성격(${RIASEC_KO[personalityRiasec]})과 흥미(${RIASEC_KO[interestRiasec]})가 유사한 방향을 가리키며, 적성(${aptDominant})과도 큰 충돌이 없습니다. 세 영역이 대체로 일관성 있게 정렬되어 있어 진로 선택 시 내적 갈등이 적을 것입니다.`,
    bridgeRoles: [],
  }
}

// ── 메인 해석 함수 ────────────────────────────────────────────────────

export function interpretPaidResult(
  hexaco: HexacoScores,
  subFacets: Record<SubFacet, number>,
  riasec: RiasecScores,
  riasecTop3: RiasecType[],
  aptitude: AptitudeScores,
): PaidInterpretation {

  // 1. HEXACO 패턴 — 상위 2요인
  const factorEntries = (Object.entries(hexaco) as [HexacoFactor, number][])
    .sort((a, b) => b[1] - a[1])
  const top2Factors = factorEntries.slice(0, 2).map(e => e[0])
  const pairKey = makePair(top2Factors[0], top2Factors[1])
  const pattern = HEXACO_PATTERNS[pairKey] ?? {
    title: '복합형',
    portrait: '여러 차원에서 균형 잡힌 성격 특성을 보입니다. 특정 영역이 두드러지기보다 다양한 상황에 유연하게 적응하는 능력이 강점입니다.',
    shadow: '뚜렷한 강점이 분산되어 있어 특정 역할에서 차별화된 인상을 남기기 어려울 수 있습니다. 의도적으로 핵심 강점 1~2가지를 선택해 깊이를 만들어가는 것이 중요합니다.',
  }

  // 2. 두드러진 하위 요인 (상위 3개 + 하위 3개)
  const sfEntries = (Object.entries(subFacets) as [SubFacet, number][])
    .sort((a, b) => b[1] - a[1])
  const topSf = sfEntries.slice(0, 3)
  const lowSf  = sfEntries.slice(-3).reverse()

  const topFacets = topSf.map(([sf, score]) => ({
    label: SF_LABEL[sf],
    score,
    insight: SF_INSIGHT[sf][0],
  }))
  const lowFacets = lowSf.map(([sf, score]) => ({
    label: SF_LABEL[sf],
    score,
    insight: SF_INSIGHT[sf][1],
  }))

  // 3. RIASEC 해석
  const code = riasecTop3.slice(0, 3).join('')
  const pairCode = riasecTop3[0] + riasecTop3[1]
  const riasecData = RIASEC_PAIRS[pairCode] ?? RIASEC_PAIRS[riasecTop3.slice(0,2).reverse().join('')] ?? {
    title: '복합 흥미형',
    portrait: '특정 유형에 강하게 치우치지 않고 다양한 활동 영역에 고루 관심이 분포합니다.',
    fits: ['융합 역할', '다양한 분야의 접점 직무'],
    misfits: ['극도로 전문화된 단일 분야'],
  }

  const { alignment, note: alignmentNote } = assessAlignment(hexaco, riasecTop3)

  // 4. 학문 적성 비율
  const aptitudeRatio = computeAptitudeRatio(aptitude)

  // 5. HEXACO × RIASEC × 적성 교차 종합 분석
  const crossDomainSynthesis = computeCrossDomainSynthesis(hexaco, riasecTop3, aptitudeRatio, pattern.title)

  // 6. 통합 결론
  const synthesisText = generateSynthesis(
    { title: pattern.title },
    { hollandCode: code, title: riasecData.title },
    aptitudeRatio,
    hexaco,
    sfEntries.slice(0, 5).map(e => e[0]),
  )

  const fusionLabel = aptitudeRatio.fusionPath3?.label ?? aptitudeRatio.fusionPath?.label
  const fusionCareers = aptitudeRatio.fusionPath3?.careers ?? aptitudeRatio.fusionPath?.careers ?? []

  return {
    headline: `${pattern.title} · ${RIASEC_PAIR_LABELS[riasecTop3[0]]} ${fusionLabel ?? aptitudeRatio.dominant}`,
    patternKey: pairKey,
    hexacoPattern: {
      title: pattern.title,
      portrait: pattern.portrait,
      shadow: pattern.shadow,
      topFacets,
      lowFacets,
      crossInsights: detectCrossInsights(hexaco),
    },
    situationalPredictions: generateSituationalPredictions(hexaco),
    riasecProfile: {
      hollandCode: code,
      title: riasecData.title,
      portrait: riasecData.portrait,
      fitEnvironments: riasecData.fits,
      misfitEnvironments: riasecData.misfits,
    },
    aptitudeBreakdown: {
      ...aptitudeRatio,
    },
    crossDomainSynthesis,
    synthesis: {
      coreIdentity: synthesisText,
      careerCompass: fusionLabel
        ? `융합 경로: ${fusionLabel} · 추천 직업: ${fusionCareers.slice(0, 3).join(', ')}`
        : `추천 방향: ${riasecData.fits.slice(0, 3).join(', ')} · 추천 전공: ${aptitudeRatio.recommended.slice(0, 3).join(', ')}`,
      growthEdge: pattern.shadow,
      alignment,
      alignmentNote,
    },
  }
}
